# Writes preview_server.luau: a TEST-ONLY server Script for the lobby (put in a Workspace temp folder in Edit, never
# saved). On Play it builds the idle drafts as KeyframeSequences in memory (KeyframeSequenceProvider, Studio only: no
# upload), builds six Prickles with the game's own builder (no player, no data) and loops: Now / Draft A / Draft B, plain
# in front and wearing the Showstopper remake test outfit behind, each with a label.
#   python make_preview.py
import os, xml.etree.ElementTree as ET
HERE = os.path.dirname(os.path.abspath(__file__))
CLIPS = {'A': f'{HERE}/out/draft_d2.rbxmx', 'B': f'{HERE}/out/draft_d3.rbxmx'}


def clip_lua(path):
    root = ET.parse(path).getroot()
    keys = sorted([e for e in root.iter('Item') if e.get('class') == 'Keyframe'],
                  key=lambda e: float(e.find('./Properties/float[@name="Time"]').text))
    keys = keys[::2] + ([keys[-1]] if (len(keys) - 1) % 2 else [])   # every 2nd key (linear easing, 30 fps): half the size
    out = []
    for k in keys:
        t = float(k.find('./Properties/float[@name="Time"]').text)
        poses = []
        for e in k.iter('Item'):
            if e.get('class') != 'Pose': continue
            name = e.find('./Properties/string[@name="Name"]').text
            cf = e.find('./Properties/CoordinateFrame')
            nums = [float(cf.find(a).text) for a in 'XYZ'] + [float(cf.find(f'R{a}{b}').text) for a in range(3) for b in range(3)]
            poses.append('{"%s",%s}' % (name, ','.join('%.4g' % v for v in nums)))
        out.append('{%.4f,{%s}}' % (t, ','.join(poses)))
    return '{' + ',\n'.join(out) + '}'


data = ',\n'.join(f'{k}={clip_lua(p)}' for k, p in CLIPS.items())
lua = r'''-- TEST ONLY (Prickles idle drafts, 2026-11-16; generated by characters/prickles/idle-arms-2026-11-16/make_preview.py).
-- Lobby only, in a Workspace temp folder, never saved. On Play: Now / Draft A / Draft B side by side, plain in front and
-- wearing the Showstopper remake test outfit (PricklesShowstopperRemake) behind. The drafts are built in memory with
-- KeyframeSequenceProvider (Studio only, nothing uploaded). Six models from the game's builder: no player, no data.
local RS, SSS = game:GetService("ReplicatedStorage"), game:GetService("ServerScriptService")
local KSP = game:GetService("KeyframeSequenceProvider")
local EmployeeRegistry = require(RS.Shared.Features.Employee.Data.EmployeeRegistry)
local EmployeeCharacterSystem = require(SSS.Features.Employee.Systems.EmployeeCharacterSystem)
local EmployeeOutfitSystem = require(RS.Shared.Features.Employee.Systems.EmployeeOutfitSystem)
local DATA = {
''' + data + r'''
}
local PARENT = { LowerTorso = "HumanoidRootPart", UpperTorso = "LowerTorso", Head = "UpperTorso",
	LeftUpperArm = "UpperTorso", LeftLowerArm = "LeftUpperArm", LeftHand = "LeftLowerArm",
	RightUpperArm = "UpperTorso", RightLowerArm = "RightUpperArm", RightHand = "RightLowerArm",
	LeftUpperLeg = "LowerTorso", LeftLowerLeg = "LeftUpperLeg", LeftFoot = "LeftLowerLeg",
	RightUpperLeg = "LowerTorso", RightLowerLeg = "RightUpperLeg", RightFoot = "RightLowerLeg" }
local function buildKfs(rows)
	local kfs = Instance.new("KeyframeSequence"); kfs.Loop = true; kfs.Priority = Enum.AnimationPriority.Action4
	for _, row in rows do
		local kf = Instance.new("Keyframe"); kf.Time = row[1]
		local made = {}
		local root = Instance.new("Pose"); root.Name = "HumanoidRootPart"; root.Weight = 0; root.Parent = kf
		made.HumanoidRootPart = root
		local byName = {}
		for _, p in row[2] do byName[p[1]] = p end
		local function make(name)
			if made[name] then return made[name] end
			local parent = make(PARENT[name])
			local p = byName[name]
			local pose = Instance.new("Pose"); pose.Name = name; pose.Weight = 1
			if p then pose.CFrame = CFrame.new(p[2], p[3], p[4], p[5], p[6], p[7], p[8], p[9], p[10], p[11], p[12], p[13]) end
			pose.Parent = parent; made[name] = pose
			return pose
		end
		for name in PARENT do make(name) end
		kf.Parent = kfs
	end
	return kfs
end
local ids = { Now = "rbxassetid://108680458550464" }
for k, rows in DATA do ids[k] = KSP:RegisterKeyframeSequence(buildKfs(rows)) end
local outfit = RS.Assets.CleanupCrew.Outfits:FindFirstChild("PricklesShowstopperRemake")
local folder = script.Parent
local spawnAt = Vector3.new(1, 0, -224)
local spawn = workspace:FindFirstChildWhichIsA("SpawnLocation", true)
if spawn then spawnAt = spawn.Position end
local function label(model, text)
	local head = model:FindFirstChild("Head"); if not head then return end
	local bb = Instance.new("BillboardGui"); bb.Size = UDim2.fromOffset(220, 40); bb.StudsOffset = Vector3.new(0, 3.2, 0)
	bb.AlwaysOnTop = true; bb.Adornee = head
	local tl = Instance.new("TextLabel"); tl.Size = UDim2.fromScale(1, 1); tl.BackgroundTransparency = 0.3
	tl.BackgroundColor3 = Color3.fromRGB(30, 24, 30); tl.TextColor3 = Color3.new(1, 1, 1); tl.TextScaled = true
	tl.Font = Enum.Font.GothamBold; tl.Text = text; tl.Parent = bb; bb.Parent = model
end
local order = { "Now", "A", "B" }
local names = { Now = "NOW", A = "DRAFT A", B = "DRAFT B" }
for row, dressed in { false, true } do
	for i, key in order do
		local model = EmployeeCharacterSystem.build(EmployeeRegistry.get("Prickles"), RS, Instance.new("Folder"))
		if model then
			model.Name = "IdlePreview_" .. key .. (dressed and "_Showstopper" or "")
			local pos = spawnAt + Vector3.new((i - 2) * 6, 3, 10 + (row - 1) * 7)
			model:PivotTo(CFrame.lookAt(pos, pos + Vector3.new(0, 0, -1)))
			local hrp = model:FindFirstChild("HumanoidRootPart"); if hrp then hrp.Anchored = true end
			model.Parent = folder
			if dressed and outfit then EmployeeOutfitSystem.fit(model, outfit, nil) end
			local hum = model:FindFirstChildOfClass("Humanoid")
			local animator = hum and (hum:FindFirstChildOfClass("Animator") or Instance.new("Animator", hum))
			if animator then
				local anim = Instance.new("Animation"); anim.AnimationId = ids[key]
				local track = animator:LoadAnimation(anim); track.Priority = Enum.AnimationPriority.Action4; track.Looped = true
				track:Play(0)
			end
			label(model, names[key] .. (dressed and " + Showstopper" or ""))
		end
	end
end
workspace:SetAttribute("IdlePreview", "ok " .. tostring(#folder:GetChildren()))
'''
open(f'{HERE}/preview_server.luau', 'w', encoding='utf-8').write(lua)
print('WROTE preview_server.luau', len(lua))
